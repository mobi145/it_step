s1 = float(input("Продажі 1: "))
s2 = float(input("Продажі 2: "))
s3 = float(input("Продажі 3: "))

# Зарплата 1-го
if 0 <= s1 <= 500:
    z1 = 200 + s1 * 0.03
elif 500 < s1 <= 1000:
    z1 = 200 + s1 * 0.05
else:
    z1 = 200 + s1 * 0.08

# Зарплата 2-го
if 0 <= s2 <= 500:
    z2 = 200 + s2 * 0.03
elif 500 < s2 <= 1000:
    z2 = 200 + s2 * 0.05
else:
    z2 = 200 + s2 * 0.08

# Зарплата 3-го
if 0 <= s3 <= 500:
    z3 = 200 + s3 * 0.03
elif 500 < s3 <= 1000:
    z3 = 200 + s3 * 0.05
else:
    z3 = 200 + s3 * 0.08

if s1 >= s2 and s1 >= s3:
    z1 += 200
    best = "1-й"
elif s2 >= s1 and s2 >= s3:
    z2 += 200
    best = "2-й"
else:
    z3 += 200
    best = "3-й"

print(f"Зарплата 1: {z1}")
print(f"Зарплата 2: {z2}")
print(f"Зарплата 3: {z3}")
print(f"Найкращий: {best}")